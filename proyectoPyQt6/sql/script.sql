CREATE TABLE CLIENTE (
    ID              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RUT             VARCHAR2(12),
    DV              CHAR(1),
    NOMBRE          VARCHAR2(100),
    APELLIDO        VARCHAR2(100),
    FECHA_NAC       DATE,
    EMAIL           VARCHAR2(150),
    TELEFONO        VARCHAR2(20),
    DIRECCION       VARCHAR2(250),
    ESTADO_CLIENTE  CHAR(1),
    LIMITE_CREDITO  NUMBER(10,2)
);